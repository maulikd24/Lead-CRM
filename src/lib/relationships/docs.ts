import { REFERENCED_BY_VALUE, RELATIONSHIPS, type EraseRule, type MergeRule, type RelationshipEntry, type TimelineRule } from "./registry";

/** docs/customer-relationships.md, generated from the registry (npm run relationships:docs). A test fails when the file is out of date. */
const path = (e: RelationshipEntry) => [...e.paths, ...(e.extraErasePaths ?? [])].map((p) => [...p.via, p.column].join(".")).join(", ");
const merge = (m: MergeRule): string =>
  m.kind === "reparent" ? (m.onlyIfAny ? "moves to the survivor (only when the duplicate has a live row)" : "moves to the survivor")
  : m.kind === "reparent_if_absent" ? `moves only if the survivor has none (else conflict: ${m.conflict})`
  : m.kind === "reparent_if_survivor_has_none" ? `moves only if the survivor has none (else conflict: ${m.conflict})`
  : m.kind === "handler" ? `special: ${m.handler}`
  : m.kind === "stay" ? `stays on the archived duplicate (${m.note})`
  : m.kind === "follows_parent" ? `travels with ${m.parent}`
  : m.note;
const erase = (e: EraseRule): string =>
  e.kind === "delete" ? `delete (step ${e.order})`
  : e.kind === "block" ? `blocks erasure (check ${e.order})`
  : e.kind === "block_then_delete" ? `blocks while invested (check ${e.blockOrder}), then delete (step ${e.deleteOrder})`
  : e.kind === "tombstone" ? "tombstone (replay key kept, data removed)"
  : e.kind === "handler" ? `facts kept, data nulled (step ${e.order})`
  : e.kind === "cascade" ? `removed with ${e.parent}`
  : `with ${e.parent}: ${e.why}`;
const timeline = (t: TimelineRule): string => ("source" in t ? `shown (${t.source})` : "foldedInto" in t ? `folded into ${t.foldedInto}` : `not shown: ${t.none}`);

export function renderRelationshipsDoc(): string {
  const lines = [
    "# Customer relationship registry",
    "",
    "Generated by `npm run relationships:docs` from `src/lib/relationships/registry.ts`. Do not edit by hand.",
    "",
    "Every table that reaches the customer (`Client`) directly, by a plain id column or through another table, and how it is merged, erased and shown on the timeline. A test (`registry.test.ts`) reads `prisma/schema.prisma` and fails when a table with a customer link is missing here.",
    "",
    "| Table | Link | Merge | Erasure | Timeline | Data class |",
    "|---|---|---|---|---|---|",
    ...RELATIONSHIPS.map((r) => `| ${r.model} | ${r.kind === "direct_fk" ? "foreign key" : r.kind === "plain_id" ? "plain id" : "indirect"} \`${path(r)}\` | ${merge(r.merge)} | ${erase(r.erase)} | ${timeline(r.timeline)} | ${r.dataClass.toLowerCase().replace("_", " ")} |`),
    "",
    "## Referenced by value (not verifiable from the schema)",
    "",
    "| Table | How it names the customer | Erasure | Why |",
    "|---|---|---|---|",
    ...REFERENCED_BY_VALUE.map((r) => `| ${r.model} | ${r.how} | ${r.erase.replace("_", " ")} | ${r.why} |`),
    "",
  ];
  return lines.join("\n");
}
