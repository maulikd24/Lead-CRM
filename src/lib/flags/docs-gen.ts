import { conflictsWith, dependsOn, effectsOf } from "./describe";
import { PROFILES, PROFILE_NAMES } from "./profiles";
import { REGISTRY, isFlagDef } from "./registry";
import { RULES } from "./validate";
import type { FlagDef, Kind } from "./types";

export const GEN_START = "<!-- flags:generated:start -->";
export const GEN_END = "<!-- flags:generated:end -->";

const cell = (parts: string[]) => (parts.length ? parts.join("; ").replace(/\|/g, "/") : "-");
const code = (s: string) => "`" + s + "`";

type Group = { title: string; blurb: string; pick: (f: FlagDef) => boolean };
const GROUPS: Group[] = [
  { title: "Screens and features: set at build", blurb: "NEXT_PUBLIC_* names are inlined into the browser bundle: changing one needs a rebuild and a redeploy.", pick: (f) => f.exposure === "public" && isFlagDef(f) },
  { title: "Features and jobs: set at run time", blurb: "Read when the server runs; a restart picks up a change.", pick: (f) => f.exposure === "server" && f.kind === "feature" },
  { title: "Outbound and AI-adjacent", blurb: "Can contact a customer, call a vendor or use an AI provider. Each needs consent enforcement (FR-10/FR-11); AI ones also need a provider key and a recorded sign-off (FR-12).", pick: (f) => f.kind === "outbound" || f.kind === "outbound-ai" },
  { title: "Safety switches and blocked flags", blurb: "A blocked flag is rejected in every profile and every environment.", pick: (f) => f.kind === "safety" || f.kind === "blocked" },
  { title: "Config values", blurb: "Enums, lists, hours, addresses and paths. Shown on the status page only when marked safe.", pick: (f) => f.kind === "config" },
  { title: "Secrets and credentials", blurb: "Presence only. No value is ever read into the docs, the status page or the Flags tab.", pick: (f) => f.kind === "secret" },
  { title: "Platform, host-provided", blurb: "Set by the host or the framework.", pick: (f) => f.kind === "platform" },
  { title: "Tests and tooling", blurb: "Opt-in real-database tests refuse a non-local database. Run one file at a time: they share the database.", pick: (f) => f.kind === "test" },
];

function defaultText(f: FlagDef): string {
  if (f.type === "bool") return "off";
  return f.default ?? "unset";
}

function table(rows: FlagDef[]): string[] {
  const out = ["| Name | When | Default | Owner | What it enables | Depends on | Conflicts with | Effects |", "| --- | --- | --- | --- | --- | --- | --- | --- |"];
  for (const f of rows) {
    const when = f.exposure === "public" ? "build" : f.process === "worker" ? "run (worker)" : f.process === "tooling" ? "tooling" : "run";
    const name = code(f.name) + (f.inFlight ? ` _(arrives with ${f.inFlight})_` : "");
    const text = f.enables.replace(/\|/g, "/") + (f.accessArea ? ` Opens area ${code(f.accessArea)}.` : "") + (f.approval ? ` **Needs approval:** ${f.approval}` : "");
    out.push(`| ${name} | ${when} | ${defaultText(f)} | ${f.owner} | ${text} | ${cell(dependsOn(f))} | ${cell(conflictsWith(f))} | ${cell(effectsOf(f))} |`);
  }
  return out;
}

export function renderGeneratedRegion(): string {
  const lines: string[] = [];
  const flags = REGISTRY.filter(isFlagDef);
  lines.push(
    GEN_START,
    "",
    "<!-- Generated by `npm run flags:docs` from src/lib/flags/registry.ts. Do not edit between these markers: change the registry and regenerate. `npm run flags:check` fails on a difference. -->",
    "",
    `The registry holds **${REGISTRY.length}** environment names: **${flags.length}** on/off switches (**${flags.filter((f) => f.exposure === "public").length}** build-time), ${REGISTRY.filter((f) => f.kind === "config").length} config values, ${REGISTRY.filter((f) => f.kind === "secret").length} credentials, ${REGISTRY.filter((f) => f.kind === "platform").length} host-provided and ${REGISTRY.filter((f) => f.kind === "test").length} test and tooling names. Names marked _arrives with_ belong to a branch that is not merged yet.`,
    "",
  );
  for (const g of GROUPS) {
    const rows = REGISTRY.filter(g.pick);
    if (!rows.length) continue;
    lines.push(`### ${g.title}`, "", g.blurb, "", ...table(rows), "");
  }

  lines.push("### Validation rules", "", "`validateFlags(env)` checks these. In a production start the safety rules (FR-05, FR-10, FR-11, FR-13, FR-14) stop the boot; every other finding is logged once and shown on the Flags tab. Set `FLAG_CHECK=warn` to downgrade a failed check (break-glass, logged loudly). In development and CI everything is reported.", "", "| Rule | Severity | Checks |", "| --- | --- | --- |");
  for (const r of RULES) lines.push(`| ${r.id} | ${r.severity} | ${r.title} |`);
  lines.push("");

  lines.push("### Profiles", "", "Five named combinations, validated in CI. Templates live in `docs/profiles/<name>.env` (names and safe values only). `1` = on, `planned` = arrives with an unmerged branch, `approval` = left off until the owner approves.", "");
  lines.push(`| Name | ${PROFILE_NAMES.join(" | ")} |`, `| --- | ${PROFILE_NAMES.map(() => "---").join(" | ")} |`);
  const used = REGISTRY.filter((f) => PROFILE_NAMES.some((p) => f.name in PROFILES[p].values || f.name in PROFILES[p].planned));
  for (const f of used) {
    const marks = PROFILE_NAMES.map((p) => {
      const d = PROFILES[p];
      if (d.needsApproval.includes(f.name)) return "approval";
      if (f.name in d.values) return f.type === "bool" ? "1" : "set";
      if (f.name in d.planned) return "planned";
      return "";
    });
    lines.push(`| ${code(f.name)} | ${marks.join(" | ")} |`);
  }
  lines.push("", ...PROFILE_NAMES.map((p) => `- **${p}**: ${PROFILES[p].purpose} ${PROFILES[p].notes}`), "", GEN_END);
  return lines.join("\n");
}

/** Replace the generated region of an existing document, or insert it after the first heading's intro when absent. */
export function applyGenerated(doc: string, region: string): string {
  const s = doc.indexOf(GEN_START);
  const e = doc.indexOf(GEN_END);
  if (s !== -1 && e !== -1 && e > s) return doc.slice(0, s) + region + doc.slice(e + GEN_END.length);
  return doc.replace(/\s*$/, "") + "\n\n" + region + "\n";
}

