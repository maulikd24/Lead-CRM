import { chromium } from "playwright";
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1280, height: 800 }, storageState: "e2e/.auth/admin.json" });
const p = await ctx.newPage();
await p.goto("http://localhost:3540/settings/sign-in", { waitUntil: "networkidle" });
console.log(await p.locator("h1").first().innerText().catch(()=>"no h1"));
console.log((await p.locator("main").innerText()).slice(0,600));
await p.locator("#domains").fill("supportify.local\nbad domain!!");
await p.getByRole("button", { name: "Save domains" }).click();
await p.waitForTimeout(1500);
console.log("after bad:", (await p.locator("[role=alert]").allInnerTexts()).join("|"));
await p.locator("#domains").fill("supportify.local, Example.com");
await p.getByRole("button", { name: "Save domains" }).click();
await p.waitForTimeout(1500);
console.log("after good:", (await p.locator("[role=status]").innerText()));
await p.screenshot({ path: "/tmp/claude-502/shots/settings-signin.png" });
await b.close();
